/* =============================================================
   switchLanguage — Update all translatable elements
   ============================================================= */
function switchLanguage(lang) {
  // Update html lang attribute
  document.documentElement.lang = lang;

  // Update all data-i18n elements (textContent)
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key]) {
      el.textContent = i18n[lang][key];
    }
  });

  // Update all data-i18n-html elements (innerHTML)
  document.querySelectorAll('[data-i18n-html]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-html');
    if (i18n[lang] && i18n[lang][key]) {
      el.innerHTML = i18n[lang][key];
    }
  });

  // Update all data-i18n-placeholder elements
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-placeholder');
    if (i18n[lang] && i18n[lang][key]) {
      el.placeholder = i18n[lang][key];
    }
  });

  // Update active button in both desktop and mobile switchers
  document.querySelectorAll('.lang-btn').forEach(function(b) {
    if (b.getAttribute('data-lang') === lang) {
      b.classList.add('active');
    } else {
      b.classList.remove('active');
    }
  });

  // Save preference
  localStorage.setItem('lang', lang);
  if (window.loadWebFonts) window.loadWebFonts(lang);
}
